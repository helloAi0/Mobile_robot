#!/usr/bin/env python3
"""Generates worlds/actor_height_test.sdf: 7 women walking in 7 lanes, each with a different root height z.

   ros2 launch mobile_robot_bringup launch_sim.launch.py world:=actor_height_test.sdf slam:=false auto:=false
Look at the Gazebo window: lane n is marked with n small red cubes. Find the lane whose woman walks with her feet ON the
floor (not floating, not sunk in), then run:   ros2 run mobile_robot_gazebo tune_actor_height.py <z of that lane>
"""
import math
import os

MAN = "https://fuel.gazebosim.org/1.0/Mingfei/models/actor/tip/files/meshes/walk.dae"
WOMAN = "https://fuel.gazebosim.org/1.0/Luca/models/FemaleVisitorWalk/tip/files/meshes/FemaleVisitorWalk.dae"
HEIGHTS = [-0.1, 0.0, 0.1, 0.2, 0.4, 0.6, 0.9]


def waypoints(pts):
    return "\n".join(f'          <waypoint><time>{t}</time><pose>{x} {y} {z} 0 0 {yaw}</pose></waypoint>' for t, x, y, z, yaw in pts)


def patrol(x1, y1, x2, y2, z, speed=0.9):
    t = math.hypot(x2 - x1, y2 - y1) / speed
    yaw, back = 0.0, 3.14
    return [(0, x1, y1, z, yaw), (round(t, 2), x2, y2, z, yaw), (round(t + 0.5, 2), x2, y2, z, back),
            (round(2 * t + 0.5, 2), x1, y1, z, back), (round(2 * t + 1, 2), x1, y1, z, yaw)]


def actor(name, mesh, pts, comment):
    return f'''    <!-- {comment} -->
    <actor name="{name}">
      <skin><filename>{mesh}</filename><scale>1.0</scale></skin>
      <animation name="walk"><filename>{mesh}</filename><interpolate_x>true</interpolate_x></animation>
      <script><loop>true</loop><delay_start>0.0</delay_start><auto_start>true</auto_start>
        <trajectory id="0" type="walk" tension="0.6">
{waypoints(pts)}
        </trajectory>
      </script>
    </actor>
'''


body = ""
for i, z in enumerate(HEIGHTS):
    y = -4.5 + i * 1.5
    for k in range(i + 1):
        body += (f'    <model name="mark_{i+1}_{k}"><static>true</static><pose>-1.0 {y - 0.5 + k * 0.18} 0.05 0 0 0</pose>'
                 f'<link name="link"><visual name="v"><geometry><box><size>0.1 0.1 0.1</size></box></geometry>'
                 f'<material><ambient>0.8 0.1 0.1 1</ambient><diffuse>0.8 0.1 0.1 1</diffuse></material></visual></link></model>\n')
    body += actor(f"test_woman_{i+1}", WOMAN, patrol(1.0, y, 4.0, y, z), f"Lane {i+1}: root height z={z}")

sdf = f'''<?xml version="1.0" ?>
<!-- Height calibration: 7 women walking in lanes 1..7 (lane n has n red cubes); z = {HEIGHTS}. GENERATED by tools/make_actor_test_world.py -->
<sdf version="1.9">
  <world name="default">
    <physics name="default_physics" type="ode"><max_step_size>0.004</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <scene><ambient>0.6 0.6 0.6 1</ambient><background>0.7 0.8 0.95 1</background><shadows>true</shadows></scene>
    <light type="directional" name="sun"><cast_shadows>true</cast_shadows><pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.85 1</diffuse><specular>0.2 0.2 0.2 1</specular><direction>-0.3 0.2 -0.9</direction></light>
    <model name="ground_plane"><static>true</static><link name="link">
      <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry></collision>
      <visual name="visual"><geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
        <material><ambient>0.6 0.6 0.6 1</ambient><diffuse>0.6 0.6 0.6 1</diffuse></material></visual></link></model>
{body}  </world>
</sdf>
'''
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "worlds", "actor_height_test.sdf"), "w").write(sdf)
print("worlds/actor_height_test.sdf written")
